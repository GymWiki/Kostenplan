const { chromium } = require("@playwright/test");
const { pdokNepRoutes } = require("./_pdok.js");
const MODUS = process.argv[2] || "script";
const DIR = "/home/user/Kostenplan/test-results/screens/flow-tester-3/";
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--no-sandbox"] });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: "nl-NL", timezoneId: "Europe/Amsterdam" });
  await pdokNepRoutes(ctx);
  const page = await ctx.newPage();
  const log = [];
  page.on("console", (m) => { if (m.type() === "error") log.push("console: " + m.text().slice(0, 200)); });
  page.on("pageerror", (e) => log.push("pageerror: " + e.message.slice(0, 200)));
  page.on("requestfailed", (r) => log.push("reqfail: " + r.url().slice(0, 120) + " " + r.failure()?.errorText));
  await page.goto(`http://localhost:3200/test-embed?tool=cmv6wdxux004qq47dowifa9j4&modus=${MODUS}`, { waitUntil: "networkidle" });
  const frame = page.frameLocator("iframe").first();
  const inp = frame.getByRole("textbox").first();
  await inp.fill("8011AB 5");
  await page.waitForTimeout(1500);
  await page.screenshot({ path: DIR + `02-${MODUS}-postcode-ingevuld.png` });
  const knoppen = await frame.locator("button, input, [role=button], label").allInnerTexts().catch(e => ["ERR " + e.message]);
  console.log("ELEMENTEN", JSON.stringify(knoppen.map(t => t.slice(0,80)).slice(0, 60)));
  console.log("LOG", log);
  await b.close();
})().catch((e) => { console.error("FOUT", e.message); process.exit(1); });
