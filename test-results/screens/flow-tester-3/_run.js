const { chromium } = require("@playwright/test");
const { pdokNepRoutes } = require("./_pdok.js");
const fs = require("fs");
const MODUS = process.argv[2] || "script";
const NAAM = process.argv[3] || "Klant Flow3 " + MODUS;
const D = "/home/user/Kostenplan/test-results/screens/flow-tester-3/";
(async () => {
  const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome", args: ["--no-sandbox"] });
  const ctx = await b.newContext({ viewport: process.env.MOB ? { width: 412, height: 915 } : { width: 1440, height: 900 }, hasTouch: !!process.env.MOB, isMobile: !!process.env.MOB, locale: "nl-NL", timezoneId: "Europe/Amsterdam" });
  await pdokNepRoutes(ctx);
  const page = await ctx.newPage();
  const logs = [];
  page.on("console", (m) => { if (m.type() === "error") logs.push("console: " + m.text().slice(0, 200)); });
  page.on("pageerror", (e) => logs.push("pageerror: " + e.message.slice(0, 200)));
  page.on("response", (r) => { if (r.status() >= 400) logs.push(`HTTP ${r.status()} ${r.url().slice(0, 120)}`); });
  await page.goto(`http://localhost:3200/test-embed?tool=cmv6wdxux004qq47dowifa9j4&modus=${MODUS}`, { waitUntil: "networkidle" });
  await page.waitForTimeout(1500);
  const f = () => page.frames().find(x => x.url().includes("/embed/"));
  await f().locator("input").first().fill("8011AB 5");
  await f().getByRole("button", { name: /Voorstraat 5/ }).click({ timeout: 10000 });
  await page.waitForTimeout(800);
  await f().locator("input[aria-label='Aantal Schutting']").fill(process.argv[4] || "10");
  await f().locator("input[aria-label='Aantal Schutting']").press("Tab");
  await f().locator("select").first().selectOption({ index: 1 });
  await page.waitForTimeout(1000);
  await page.screenshot({ path: D + `m06-${MODUS}-invoer.png` });
  const tekst1 = await f().locator("body").innerText();
  const samenvatting = tekst1.slice(tekst1.indexOf("Jouw kostenraming"), tekst1.indexOf("Jouw kostenraming") + 500);
  console.log("RAMING", samenvatting.replace(/\n+/g, " | "));
  await f().getByRole("button", { name: "Offerte aanvragen" }).click({ timeout: 10000 });
  await page.waitForTimeout(1000);
  await page.screenshot({ path: D + `m07-${MODUS}-formulier.png` });
  await f().locator("input[name='naam']").fill(NAAM);
  await f().locator("input[name='email']").fill(`klant-${MODUS}-flow3@test.kostenplan.nl`);
  await f().locator("input[name='telefoonnummer']").fill("06 98765432");
  await page.screenshot({ path: D + `m08-${MODUS}-ingevuld.png` });
  await f().getByRole("button", { name: "Versturen" }).click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: D + `m09-${MODUS}-na-versturen.png` });
  const na = await f().locator("body").innerText().catch(() => "GEEN FRAME");
  console.log("NA VERSTUREN", na.slice(0, 700).replace(/\n+/g, " | "));
  console.log("LOGS", logs);
  fs.writeFileSync(D + `_resultaat-${MODUS}.json`, JSON.stringify({ naam: NAAM, raming: samenvatting, tekstNa: na.slice(0, 1500) }, null, 1));
  await b.close();
})().catch((e) => { console.error("FOUT", e.message.slice(0, 400)); process.exit(1); });
